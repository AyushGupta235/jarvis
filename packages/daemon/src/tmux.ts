import { execFile, spawn } from 'node:child_process';
import { readFileSync, existsSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';

const SEP = ':::J:::';

export interface LiveSession {
  name: string;
  jarvisId: string | null;
  activity: number; // epoch ms
  attached: number;
  currentPath: string;
  currentCommand: string;
  panePid: number | null;
  created: number;
}

const LIST_FORMAT = [
  '#{session_name}',
  '#{@jarvis_id}',
  '#{session_activity}',
  '#{session_attached}',
  '#{pane_current_path}',
  '#{pane_current_command}',
  '#{pane_pid}',
  '#{session_created}',
].join(SEP);

export function parseSessionList(stdout: string): LiveSession[] {
  const out: LiveSession[] = [];
  for (const line of stdout.split('\n')) {
    if (!line.trim()) continue;
    const [name, jid, act, att, path, cmd, pid, created] = line.split(SEP);
    if (!name) continue;
    out.push({
      name,
      jarvisId: jid ? jid : null,
      activity: Number(act) * 1000 || 0,
      attached: Number(att) || 0,
      currentPath: path ?? '',
      currentCommand: cmd ?? '',
      panePid: pid ? Number(pid) : null,
      created: Number(created) * 1000 || 0,
    });
  }
  return out;
}

export class Tmux {
  constructor(
    readonly bin: string,
    /** `-L` socket name; null means the default socket. */
    readonly socket: string | null,
    readonly confPath: string | null,
    private readonly env: NodeJS.ProcessEnv,
  ) {}

  baseArgs(): string[] {
    const a: string[] = ['-u'];
    if (this.socket) a.push('-L', this.socket);
    if (this.confPath) a.push('-f', this.confPath);
    return a;
  }

  run(args: string[]): Promise<string> {
    return new Promise((resolve, reject) => {
      execFile(this.bin, [...this.baseArgs(), ...args], { env: this.env, timeout: 5000, maxBuffer: 16 << 20 }, (err, stdout, stderr) => {
        if (err) reject(new Error(`tmux ${args[0]}: ${(stderr || err.message).trim()}`));
        else resolve(stdout);
      });
    });
  }

  /** Run a tmux command with data on stdin (e.g. `load-buffer -`). */
  runInput(args: string[], input: string): Promise<string> {
    return new Promise((resolve, reject) => {
      const p = spawn(this.bin, [...this.baseArgs(), ...args], { env: this.env });
      let out = '';
      let err = '';
      p.stdout.on('data', (d) => (out += d));
      p.stderr.on('data', (d) => (err += d));
      p.on('error', reject);
      p.on('close', (code) => (code === 0 ? resolve(out) : reject(new Error(`tmux ${args[0]}: ${err.trim()}`))));
      p.stdin.end(input);
    });
  }

  async listSessions(): Promise<LiveSession[]> {
    try {
      return parseSessionList(await this.run(['list-sessions', '-F', LIST_FORMAT]));
    } catch (e) {
      const msg = (e as Error).message;
      if (/no server running|error connecting|No such file or directory/i.test(msg)) return [];
      throw e;
    }
  }

  /** `=` prefix makes tmux match the session name exactly instead of by prefix. */
  static target(name: string): string {
    return `=${name}`;
  }

  /** Pane-level commands need a pane target; `=name:` resolves to the session's active pane. */
  static paneTarget(name: string): string {
    return `=${name}:`;
  }
}

/**
 * The user's ~/.tmux.conf minus plugin machinery. tmux-continuum would otherwise auto-restore the
 * user's default-socket snapshot into the Jarvis server and overwrite that snapshot every 15 minutes
 * with Jarvis sessions. `source-file ~/.tmux.conf` reload bindings are pointed at the Jarvis config.
 */
export function filterUserConf(text: string, jarvisConfPath: string): string {
  const out: string[] = ['# Generated by jarvisd from ~/.tmux.conf (plugins removed). Do not edit.'];
  for (const line of text.split('\n')) {
    const t = line.trim();
    if (/@plugin|@continuum|@resurrect/.test(t)) continue;
    if (/^run(-shell)?\b/.test(t) && /tpm|plugins/.test(t)) continue;
    out.push(line.replace(/~\/\.tmux\.conf|\$HOME\/\.tmux\.conf/g, jarvisConfPath));
  }
  return out.join('\n') + '\n';
}

export function jarvisTmuxConf(userConfPath: string, shell: string): string {
  return `# Generated by jarvisd. Do not edit; it is rewritten on every daemon start.
source-file -q "${userConfPath}"

set -g default-shell "${shell}"
set -g default-terminal "tmux-256color"
set -g status off
set -g mouse on
set -g history-limit 50000
set -s escape-time 10
set -s extended-keys on
set -g focus-events on
set -g allow-passthrough on
set -g set-clipboard on
set -g copy-command "pbcopy"
set -as terminal-features ',xterm*:RGB:clipboard:hyperlinks:extkeys:focus:sync'
set -g destroy-unattached off
set -g exit-empty off
set -g window-size latest
set -g aggressive-resize on
set -g remain-on-exit off
set-environment -g COLORTERM truecolor
`;
}

export function writeTmuxConfs(home: string, shell: string): string {
  const confPath = join(home, 'tmux.conf');
  const userOut = join(home, 'tmux.user.conf');
  const userConf = join(homedir(), '.tmux.conf');
  const text = existsSync(userConf) ? readFileSync(userConf, 'utf8') : '';
  writeFileSync(userOut, filterUserConf(text, confPath));
  writeFileSync(confPath, jarvisTmuxConf(userOut, shell));
  return confPath;
}
