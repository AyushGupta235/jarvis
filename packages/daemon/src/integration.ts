import { chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';

/** Claude Code hook events Jarvis listens to. All are async, so they never slow the agent down. */
export const CLAUDE_HOOK_EVENTS = [
  'SessionStart', 'UserPromptSubmit', 'PreToolUse', 'PostToolUse', 'PostToolUseFailure', 'PermissionRequest',
  'Notification', 'Stop', 'StopFailure', 'SubagentStart', 'SubagentStop', 'PreCompact', 'PostCompact',
  'PostModelSwitch', 'SessionEnd',
] as const;

const TOOL_EVENTS = new Set(['PreToolUse', 'PostToolUse', 'PostToolUseFailure', 'PermissionRequest']);

export interface IntegrationPaths {
  claudeSettings: string;
  hookScript: string;
  statusScript: string;
}

function userStatusLine(): { command: string; padding?: number } | null {
  try {
    const s = JSON.parse(readFileSync(join(homedir(), '.claude', 'settings.json'), 'utf8')) as {
      statusLine?: { type?: string; command?: string; padding?: number };
    };
    if (s.statusLine?.type === 'command' && s.statusLine.command) return { command: s.statusLine.command, padding: s.statusLine.padding };
  } catch { /* no user settings */ }
  return null;
}

/**
 * Writes the shims Jarvis passes to Claude via `--settings` for sessions it launches. Your
 * ~/.claude/settings.json is never modified: these hooks are added on top of yours, and the status line
 * tap forwards the JSON to jarvisd and then runs your own status line command unchanged.
 */
export function writeIntegration(home: string, socketPath: string): IntegrationPaths {
  const bin = join(home, 'bin');
  mkdirSync(bin, { recursive: true });
  const hookScript = join(bin, 'jarvis-hook');
  const statusScript = join(bin, 'jarvis-statusline');
  const original = join(bin, 'statusline-original');

  writeFileSync(hookScript, `#!/bin/sh
# Generated by jarvisd. Forwards a Claude Code hook event to jarvisd; never fails the agent.
[ -n "$JARVIS_SESSION" ] || exit 0
curl -s -m 2 --unix-socket "\${JARVIS_SOCKET:-${socketPath}}" -H 'content-type: application/json' \\
  --data-binary @- "http://jarvis/ingest/claude-hook?s=$JARVIS_SESSION" >/dev/null 2>&1
exit 0
`);
  const sl = userStatusLine();
  writeFileSync(original, sl ? `#!/bin/sh\n# Your status line from ~/.claude/settings.json\n${sl.command}\n` : '#!/bin/sh\nexit 0\n');
  writeFileSync(statusScript, `#!/bin/sh
# Generated by jarvisd. Sends the status line JSON to jarvisd, then runs your own status line unchanged.
input=$(cat)
if [ -n "$JARVIS_SESSION" ]; then
  printf '%s' "$input" | curl -s -m 1 --unix-socket "\${JARVIS_SOCKET:-${socketPath}}" -H 'content-type: application/json' \\
    --data-binary @- "http://jarvis/ingest/claude-status?s=$JARVIS_SESSION" >/dev/null 2>&1 &
fi
printf '%s' "$input" | "${original}"
`);
  for (const f of [hookScript, statusScript, original]) chmodSync(f, 0o755);

  const hook = { type: 'command', command: hookScript, async: true, timeout: 5 };
  const hooks: Record<string, unknown[]> = {};
  for (const ev of CLAUDE_HOOK_EVENTS) hooks[ev] = [TOOL_EVENTS.has(ev) ? { matcher: '*', hooks: [hook] } : { hooks: [hook] }];
  const settings = {
    hooks,
    statusLine: { type: 'command', command: statusScript, ...(sl?.padding !== undefined ? { padding: sl.padding } : {}) },
  };
  const claudeSettings = join(home, 'claude-settings.json');
  writeFileSync(claudeSettings, JSON.stringify(settings, null, 2));
  return { claudeSettings, hookScript, statusScript };
}

export function integrationReady(p: IntegrationPaths): boolean {
  return existsSync(p.claudeSettings) && existsSync(p.hookScript);
}
